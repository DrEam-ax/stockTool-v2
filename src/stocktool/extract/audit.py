"""「用他的框架检验你的操作」—— 不是替你操作。

这是产品最关键的一步，也是对"私人军师"最诚实的用法：

  ✗ 「这位大V会买 XX 吗？」        → 这是**预测**，会错、会过期，
                                  而且把他变成了荐股机器人（他最恨的东西）
  ✓ 「我 7/20 跌到 0.8471 加仓了，帮我用他的框架检验一下」
                                → 这是**审计**，框架可复用、不承诺收益，
                                  而且用户获得的是一套自己的判断力

差别在提示词的立场：**他坐在对面审你的单，而不是替你下单。**

实测有效的输出形态（来自真实使用）：

  | 你的操作                | 我用他的框架怎么检验                |
  |------------------------|-----------------------------------|
  | 7/20 跌到 0.8471 加仓   | 破位二分法 → 低位破位该扛 → 做对了   |
  | 稀有金属的性质           | 周期成长股？→ 否，纯成长股，降低预期 |
  | 锂矿在你的持仓里          | 回避内卷股 → 锂矿是内卷泥潭，要盯     |
  | 290008 这只基金          | 不见业绩不撒鹰 → 主动基金负超额，工具不合格 |

注意最后一条：框架不仅能判对错，还能判**工具是否合格**。
"""

from __future__ import annotations

AUDIT_PROMPT = """你现在以「{name}」的框架，**检验**下面这些操作。

# 你的身份与立场（很重要）

你不是在预测，也不是在替人做决定。**你坐在对面审他这笔单子。**

- 不要说「{name}会买 XX」——那是在预测他的行为，不是你的任务。
  但**允许**给方向：按框架看，哪些板块/基金更值得考虑、哪些是典型的错误动作。
  给方向时要带上用的是哪条方法论，以及它什么时候会失效。
- 你要做的是：拿他的框架逐条比对，说清**这笔操作符合还是违背他的方法**。
- 结论可以是「做对了」「做错了」「这么做没错但有个前提没验证」「这不是他关心的维度」。
- 框架判不了的地方（例如涉及他自己的资金规模、税费），直接说判不了。

# 判断纪律

1. **先看这笔操作触发了哪条框架，再下结论。** 不许凭感觉说"做得不错"。
2. **区分「做对了」和「结果好」。** 低位破位加仓做对了，但可能还是亏——
   那是市场的事，不是方法的事。要分开说。
3. **工具不合格也是结论。** 例如主动基金长期负超额，按「不见业绩不撒鹰」
   就是工具不合格，跟择时对错无关。
4. **该说不知道就说不知道。** 需要当前数据（价格、业绩、政策）才能判断的，
   标出来「这里需要查证」，不要编。
5. **指出用户没问到的风险。** 这是检验最有价值的部分。

# 输出格式

先一句话总评，然后用这个表格逐条检验：

| 你的操作 | 用他的框架怎么检验 |
|---|---|
| （原样引用用户的操作） | （哪条框架 → 结论） |

表格之后：
- **需要你查证的**：列出为了给准结论还缺哪些数据
- **他大概会补一句什么**：用他的语气说一句（这是他的风格，不是建议）

---

# 待检验的操作

{operations}

# 相关背景

{context}
"""


def render_audit_prompt(name: str, operations: str, context: str = "（无）") -> str:
    # 同 persona：提示词含表格与 JSON，绝不能用 str.format()
    return (AUDIT_PROMPT
            .replace("{name}", name)
            .replace("{operations}", operations.strip() or "（用户没写具体操作）")
            .replace("{context}", context.strip() or "（无）"))


def build_audit_request(persona_prompt: str, operations: str,
                        context: str = "（无）", name: str = "这位大V") -> str:
    """拼出完整请求：角色框架 + 检验任务。

    角色框架（persona_prompt）必须放在前面，检验任务放后面 ——
    先让他"成为"这个人，再让他干活。反过来会让模型用通用视角回答。
    """
    if not persona_prompt:
        raise SystemExit("没有决策框架，先跑 profile-author")
    return f"{persona_prompt}\n\n---\n\n{render_audit_prompt(name, operations, context)}"
