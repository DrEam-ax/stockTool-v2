/**
 * 「用他的框架检验你的操作」—— 不是替你操作，也不是预测。
 *
 * 这是产品最关键的一步，也是对"私人军师"最诚实的用法：
 *
 *   ✗ 「这位大V会买 XX 吗？」  → 这是**预测**，会错、会过期，
 *                              而且把他变成荐股机器人（他最恨的东西）
 *   ✓ 「我 7/20 跌到 0.8471 加仓了，帮我用他的框架检验一下」
 *                          → 这是**审计**，框架可复用、不承诺收益，
 *                              用户获得的是一套自己的判断力
 *
 * 差别在提示词的立场：**他坐在对面审你的单，而不是替你下单。**
 *
 * 实测有效的输出形态：
 *   | 你的操作              | 我用他的框架怎么检验                 |
 *   |----------------------|-------------------------------------|
 *   | 7/20 跌到 0.8471 加仓 | 破位二分法 → 低位破位该扛 → 做对了    |
 *   | 290008 这只基金        | 不见业绩不撒鹰 → 主动基金负超额，工具不合格 |
 */

export interface AuditOptions {
  /** 军师的名字，用于渲染提示词 */
  name: string
  /** 用户的操作，一行一条 */
  operations: string
  /** 补充背景（持仓、成本、时间等） */
  context?: string
  /** 是否有联网工具可用 —— 决定提示词里"查证"的口径 */
  hasTools?: boolean
}

/**
 * 检验模式的**系统提示词**（不含用户操作）。
 *
 * 为什么要拆出来：App 里用户的操作是**对话消息**。
 * 如果塞进 system prompt，多轮追问时会把第一次的操作一直带着，
 * 模型会反复"检验"已经说过的那几笔。
 * CLI 场景用下面的 buildAuditPrompt 一次性拼完整即可。
 */
export function buildAuditSystemPrompt(
  systemPrompt: string,
  opts: { name: string; context?: string; hasTools?: boolean },
): string {
  const context = (opts.context ?? '').trim() || '（无）'
  const name = opts.name

  const checkClause = opts.hasTools === false
    ? '**需要当前数据（价格、业绩、政策）才能判断的，标出来「这里需要查证」，不要编。**'
    : '**需要当前数据（价格、业绩、政策）才能判断的，先调用工具查；查不到就标「这里需要查证」，不要编。**'

  return `${systemPrompt}

---

# 当前任务：检验用户的操作

用户会在对话里贴出他的**实际操作**（买入/加仓/减仓/持有一个方向或基金）。
你要用「${name}」的框架逐条**检验**它们。

# 你的身份与立场（很重要）

你不是在预测，也不是在替人做决定。**你坐在对面审他这笔单子。**

- 不要说「${name}会买 XX」——那是在预测他的行为，不是你的任务。
  但**允许**给方向：按框架看，哪些板块/基金更值得考虑、哪些是典型的错误动作。
  给方向时要带上用的是哪条方法论，以及它什么时候会失效。
- 你要做的是：拿他的框架逐条比对，说清**这笔操作符合还是违背他的方法**。
- 结论可以是「做对了」「做错了」「这么做没错但有个前提没验证」「这不是他关心的维度」。
- 框架判不了的地方（例如涉及他自己的资金规模、税费），直接说判不了。

# 判断纪律

1. **先看这笔操作触发了哪条框架，再下结论。** 不许凭感觉说"做得不错"。
   引用框架时要**用它的名字**（例：按「破位二分法」）。
2. **区分「做对了」和「结果好」。** 低位破位加仓做对了，但可能还是亏——
   那是市场的事，不是方法的事。要分开说。
3. **工具不合格也是结论。** 例如主动基金长期负超额，按「不见业绩不撒鹰」
   就是工具不合格，跟择时对错无关。
4. ${checkClause}
5. **指出用户没问到的风险。** 这是检验最有价值的部分。
   特别注意**操作之间的矛盾**（例：一边说死守，一边又减了仓）。

# 输出格式

先一句话总评，然后用这个表格逐条检验：

| 你的操作 | 用他的框架怎么检验 |
|---|---|
| （原样引用用户的操作） | （哪条框架 → 结论） |

表格之后：
- **需要你查证的**：列出为了给准结论还缺哪些数据
- **他大概会补一句什么**：用他的语气说一句（这是他的风格，不是建议）

---

# 用户提供的背景（持仓/成本等，可能为空）

${context}
`
}

/** CLI / 测试用法：一次性拼出「角色 + 检验任务 + 操作」 */
export function buildAuditPrompt(systemPrompt: string, opts: AuditOptions): string {
  const operations = opts.operations.trim() || '（用户没写具体操作）'
  return `${buildAuditSystemPrompt(systemPrompt, opts)}

---

# 待检验的操作

${operations}
`
}
