/**
 * 版本号同步：package.json → android/version.properties
 *
 * 为什么需要这一步：
 *   以前我改 APK 文件名（v1.0 / v1.1 / v1.2…）却忘了改 build.gradle，
 *   结果**文件名是 v1.3，包内 versionName 还是 1.0**。
 *   装机时 Android 只显示包内的版本号，用户完全分不清装的是哪一版；
 *   而且 versionCode 一直是 1，系统会认为它们就是同一个版本。
 *
 * 现在只维护一个地方：package.json 的 version。
 * 其余全部由这个脚本推导。
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const APP = resolve(HERE, '..')
const PKG = resolve(APP, 'package.json')
const ANDROID = resolve(APP, 'android')
const OUT = resolve(ANDROID, 'version.properties')
const WEB_VERSION = resolve(APP, 'src', 'version.ts')

const pkg = JSON.parse(readFileSync(PKG, 'utf8'))
const version = String(pkg.version || '0.0.0')

const [major = 0, minor = 0, patch = 0] = version
  .split('.')
  .map((n) => parseInt(n, 10) || 0)

// Android 用 versionCode 判断"是不是新版本"，必须是单调递增的整数。
// 编码方式：major*10000 + minor*100 + patch
const versionCode = major * 10000 + minor * 100 + patch

writeFileSync(
  OUT,
  `# Generated by scripts/sync-version.mjs from package.json -- DO NOT EDIT\n` +
    `# NOTE: kept pure ASCII because Java's Properties.load() reads ISO-8859-1;\n` +
    `# a UTF-8 comment here would come out garbled (harmless but confusing).\n` +
    `versionCode=${versionCode}\n` +
    `versionName=${version}\n`,
  'utf8',
)

// 让 Web 端也能显示版本 —— 用户要能在 App 里直接看到自己装的是哪一版
writeFileSync(
  WEB_VERSION,
  `/** 由 scripts/sync-version.mjs 生成，不要手改。来源：package.json */\n` +
    `export const APP_VERSION = '${version}'\n` +
    `export const APP_VERSION_CODE = ${versionCode}\n` +
    `export const APP_BUILD_DATE = '${new Date().toISOString().slice(0, 10)}'\n`,
  'utf8',
)

console.log(`  版本同步完成：${version}  (versionCode=${versionCode})`)
console.log(`    → android/version.properties`)
console.log(`    → src/version.ts`)
